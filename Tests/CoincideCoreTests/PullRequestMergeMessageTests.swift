import Foundation
import Testing
@testable import CoincideCore

// Ported from T3's mergeMessage.test.ts.
@Test func mergeMessageRemovesAgentTrailersAndFootersKeepingHumans() {
    let message = ["Details about Claude support.", "", "", "Co-authored-by: Alice <alice@example.com>", "Co-authored-by: Claude <noreply@anthropic.com>",
                   "* Co-authored-by: Codex <noreply@openai.com>", "co-authored-by: Cursor <cursoragent@cursor.com>", "Co-authored-by: Copilot <copilot@github.com>",
                   "", "🤖 Generated with [Claude Code](https://claude.ai/code)"].joined(separator: "\n")
    #expect(PullRequestMergeMessage.removeAgentCredits(message) == "Details about Claude support.\n\n\nCo-authored-by: Alice <alice@example.com>")
}

@Test func mergeMessagePreservesUnknownIdentitiesHumansNamedAfterAgentsAndProse() {
    let message = ["Co-authored-by: Claude <claude@example.com>", "Co-authored-by: Alice <noreply@github.com>", "Co-authored-by: Release Bot <release@example.com>",
                   "Generated by our new Claude integration.", "Generated with [Claude Code](https://example.com)", ""].joined(separator: "\n")
    #expect(PullRequestMergeMessage.removeAgentCredits(message) == message)
}

@Test func mergeMessagePreservesFencesQuotesAndFalseClosingFences() {
    let example = "Co-authored-by: Claude <noreply@anthropic.com>"
    let message = "Example:\n\n```text\n\(example)\n```\n\n> \(example)\n\n\(example)"
    #expect(PullRequestMergeMessage.removeAgentCredits(message) == "Example:\n\n```text\n\(example)\n```\n\n> \(example)")
    for line in ["``` text ```", "    ```", "\t~~~"] {
        #expect(PullRequestMergeMessage.removeAgentCredits("\(line)\n\n\(example)") == line)
    }
    for fence in ["```", "~~~"] {
        let content = "\(fence)text\n\(fence) trailing text\n\(example)\n    \(fence)\n\(example)\n\(fence.prefix(2))\n\(example)\n   \(fence)\(fence.first!) \t"
        #expect(PullRequestMergeMessage.removeAgentCredits("\(content)\n\n\(example)") == content)
    }
}

@Test func mergeMessagePreservesCRLFAndCanBecomeEmpty() {
    #expect(PullRequestMergeMessage.removeAgentCredits("Details\r\n\r\nCo-authored-by: Claude <noreply@anthropic.com>\r\nCo-authored-by: Alice <alice@example.com>")
            == "Details\r\n\r\nCo-authored-by: Alice <alice@example.com>")
    #expect(PullRequestMergeMessage.removeAgentCredits("Co-authored-by: Claude <noreply@anthropic.com>\n\nGenerated by Codex\n") == "")
    #expect(PullRequestMergeMessage.removeAgentCredits("Co-authored-by: GitHub Copilot <noreply@github.com>") == "")
}
